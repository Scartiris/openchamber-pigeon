LOCALE_ORDER = ["en", "zh-CN", "zh-TW", "de", "fr", "es", "ja", "ko", "pl", "pt-BR", "uk", "tr"]


def ts_string(value: str) -> str:
    return "'" + value.replace("\\", "\\\\").replace("'", "\\'") + "'"


def inject(file_path: Path, rows: list[tuple], locale_index: int) -> int:
    text = file_path.read_text(encoding="utf-8")
    added = 0
    for row in rows:
        key = row[0]
        value = row[1 + locale_index]
        pattern = re.compile(rf"'{re.escape(key)}'\\s*:")
        if pattern.search(text):
            continue
        entry = f"  {ts_string(key)}: {ts_string(value)},\n"
        # Prefer the exported dictionary's close, not a trailing type export.
        match = re.search(r"\n\} as const;", text)
        if not match:
            match = re.search(r"\n\};", text)
        if not match:
            raise SystemExit(f"Cannot find dict close in {file_path}")
        # If there are multiple `} as const;`, take the last one before any trailing exports.
        candidates = list(re.finditer(r"\n(\} as const;|\};)", text))
        if not candidates:
            raise SystemExit(f"Cannot find dict close in {file_path}")
        # Choose the close that is followed only by type exports / blank lines.
        chosen = None
        for cand in candidates:
            tail = text[cand.end():]
            if re.fullmatch(r"(?:\s*(?:export type[^\n]+|/\*[^*]*\*/|//.*)?)", tail) or re.match(
                r"\s*export type ", tail
            ):
                chosen = cand
                break
        if chosen is None:
            chosen = candidates[-1]
        insert_at = chosen.start() + 1
        text = text[:insert_at] + entry + text[insert_at:]
        added += 1
    if added:
        file_path.write_text(text, encoding="utf-8")
    return added


def main() -> None:
    total = 0
    for index, locale in enumerate(LOCALE_ORDER):
        settings_file = ROOT / f"{locale}.settings.ts"
        main_file = ROOT / f"{locale}.ts"
        if locale == "pt-BR":
            settings_file = ROOT / "pt-BR.settings.ts"
            main_file = ROOT / "pt-BR.ts"
        total += inject(settings_file, SETTINGS_ROWS, index)
        total += inject(main_file, MAIN_ROWS, index)
        print(f"{locale}: settings={settings_file.name} main={main_file.name}")
    print(f"Injected {total} key occurrences")


if __name__ == "__main__":
    main()
